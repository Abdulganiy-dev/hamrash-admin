"""Builds run_all.sql: every access test in one script for the Supabase SQL editor.

Each test normally ends by raising its report as an error, which rolls it back
but also stops the editor. Here each test body runs inside an inner block that
is rolled back on purpose; the report is saved to a temp table, and one final
SELECT shows every report. Nothing the tests create is kept.

Run after changing any test:  python3 supabase/tests/build_run_all.py
"""
import pathlib
import re

here = pathlib.Path(__file__).parent
tests = sorted(p for p in here.glob("[0-9][0-9]_*_test.sql"))

END = re.compile(
    r"\n  execute 'reset role';\n  raise exception 'TEST REPORT \(all changes rolled back\):%', v_log;\nend;\n\$test\$;\s*$"
)

parts = [
    "-- GENERATED by build_run_all.py — do not edit by hand.\n"
    "-- Paste into the Supabase SQL editor and run: one row per test, nothing is kept.\n\n"
    "create temp table if not exists test_reports (test text primary key, report text);\n"
    "truncate test_reports;\n"
]
for path in tests:
    sql = path.read_text()
    start = sql.index("do $test$")
    body = sql[start:]
    decl_end = body.index("\nbegin\n")
    body = body[:decl_end] + "\nbegin\n  begin\n" + body[decl_end + len("\nbegin\n"):]
    if not END.search(body):
        raise SystemExit(f"{path.name}: unexpected ending, can't wrap it")
    name = path.stem.replace("_access_test", "")
    ending = (
        "\n  raise exception 'ROLLBACK';\n"
        "  exception when others then\n"
        "    if sqlerrm <> 'ROLLBACK' then\n"
        "      v_log := v_log || E'\\nERROR (test stopped early): ' || sqlerrm;\n"
        "    end if;\n"
        "  end;\n"
        f"  insert into test_reports values ('{name}', v_log);\n"
        "end;\n$test$;\n"
    )
    body = END.sub(lambda _: ending, body)  # a function, so backslashes are kept as written
    parts.append(f"\n-- ── {path.name} ──\n" + body)

parts.append(
    "\nselect test,\n"
    "       (length(report) - length(replace(report, 'PASS ', ''))) / 5 as passed,\n"
    "       (length(report) - length(replace(report, 'FAIL ', ''))) / 5\n"
    "         + (length(report) - length(replace(report, 'ERROR ', ''))) / 6 as failed,\n"
    "       report\n"
    "from test_reports order by test;\n"
)
(here / "run_all.sql").write_text("".join(parts))
print(f"wrote run_all.sql with {len(tests)} tests")
